    private void carregarCombos() {
   // Carrega apenas os Fornecedores
    service.FornecedorDAO fornecedorDAO = new service.FornecedorDAO();
    java.util.List<model.Fornecedor> fornecedores = fornecedorDAO.listarTodos();
    cbFornecedor.removeAllItems();
    if (fornecedores != null) {
        for (model.Fornecedor f : fornecedores) {
            // Adiciona o ID e Nome do fornecedor na caixa de seleção
            cbFornecedor.addItem(f.getId() + " - " + f.getNome()); 
        }
    }
}
