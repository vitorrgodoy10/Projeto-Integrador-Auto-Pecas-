    private void btnRegistrarCompraActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarCompraActionPerformed
        // TODO add your handling code here:
 String itemFornecedor = (String) cbFornecedor.getSelectedItem();
String skuDigitado = txtSKU.getText().trim(); // Usa o campo de texto do SKU

if (itemFornecedor == null || skuDigitado.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Selecione um fornecedor e informe o SKU!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
    return;
}

if (txtQuantidade.getText().trim().isEmpty() || txtCustoUnitario.getText().trim().isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Por favor, preencha todos os campos da compra!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
    return;
}

try {
    int idFornecedor = Integer.parseInt(itemFornecedor.split(" - ")[0].trim());
    int quantidade = Integer.parseInt(txtQuantidade.getText().trim());
    double precoCusto = Double.parseDouble(txtCustoUnitario.getText().trim().replace(",", "."));

    service.PecaDAO pecaDAO = new service.PecaDAO();
    // Busca no banco se o SKU já existe
    model.Peca peca = pecaDAO.buscarPorSKU(skuDigitado);

    int idPeca;
    if (peca != null) {
        idPeca = peca.getId();
    } else {
        // Se não existir, você pode solicitar o nome para cadastrar na hora
        String nomeNovaPeca = javax.swing.JOptionPane.showInputDialog(this, "SKU não encontrado. Digite o nome da nova peça para cadastrá-la:");
        if (nomeNovaPeca == null || nomeNovaPeca.trim().isEmpty()) {
            return; // Cancela se não informar o nome
        }
        
        model.Peca novaPeca = new model.Peca();
        novaPeca.setSku(skuDigitado); // ou o campo correspondente no seu model
        novaPeca.setNome(nomeNovaPeca);
       
        idPeca = pecaDAO.cadastrar(novaPeca); // Retorna o ID gerado
    }

    // Registra a compra normalmente com o idFornecedor e idPeca
    service.CompraDAO dao = new service.CompraDAO();
    boolean sucesso = dao.registrarCompra(idPeca, idFornecedor, quantidade, precoCusto);

    if (sucesso) {
        javax.swing.JOptionPane.showMessageDialog(this, "Compra registrada e estoque atualizado com sucesso!", "Sucesso", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        txtSKU.setText("");
        txtQuantidade.setText("");
        txtCustoUnitario.setText("");
    }
} catch (NumberFormatException ex) {
    javax.swing.JOptionPane.showMessageDialog(this, "Valores numéricos inválidos!", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
    }//GEN-LAST:event_btnRegistrarCompraActionPerformed
} 
