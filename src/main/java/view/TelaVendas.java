    private void btnRegistrarVendaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarVendaActionPerformed
        // TODO add your handling code here:
     String skuDigitado = txtSku.getText().trim();
    String qtdTexto = txtQuantidade.getText().trim();
    String precoTexto = txtPrecoUnitario.getText().trim();

    // 1. Validação de campos vazios
    if (skuDigitado.isEmpty() || qtdTexto.isEmpty() || precoTexto.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, preencha o SKU, Quantidade e Preço Unitário!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    try {
        int quantidadeVenda = Integer.parseInt(qtdTexto);
        double precoVenda = Double.parseDouble(precoTexto.replace(",", "."));

        if (quantidadeVenda <= 0 || precoVenda < 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "A quantidade deve ser maior que zero e o preço não pode ser negativo.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. Busca a peça pelo SKU para verificar estoque
        service.PecaDAO pecaDAO = new service.PecaDAO();
        model.Peca peca = pecaDAO.buscarPorSKU(skuDigitado);

        if (peca == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Peça com o SKU '" + skuDigitado + "' não foi encontrada!", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // 3. Validação de Estoque Suficiente
        if (peca.getQuantidade() < quantidadeVenda) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Estoque insuficiente!\nEstoque atual: " + peca.getQuantidade() + " unidades.\nQuantidade solicitada: " + quantidadeVenda + " unidades.", 
                "Aviso de Estoque", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 4. Executa o registro da venda
        service.VendaDAO vendaDAO = new service.VendaDAO();
        boolean sucesso = vendaDAO.registrarVenda(peca.getId(), quantidadeVenda, precoVenda);

        if (sucesso) {
            double valorTotal = quantidadeVenda * precoVenda;
            
            // Exibe o total no campo txtValorTotal
            txtValorTotal.setText(String.format("R$ %.2f", valorTotal));

            javax.swing.JOptionPane.showMessageDialog(this, 
                "Venda registrada com sucesso!\nValor Total: R$ " + String.format("%.2f", valorTotal), 
                "Sucesso", 
                javax.swing.JOptionPane.INFORMATION_MESSAGE);

            // Limpa os campos
            txtSku.setText("");
            txtQuantidade.setText("");
            txtPrecoUnitario.setText("");
            txtCodigoVendaMl.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao registrar a venda no banco de dados.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        }

    } catch (NumberFormatException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Informe valores numéricos válidos para quantidade e preço!", "Erro de Validação", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnRegistrarVendaActionPerformed

