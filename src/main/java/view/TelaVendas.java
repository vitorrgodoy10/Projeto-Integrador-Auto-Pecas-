    /**
     * Método auxiliar (FORA do construtor)
     */
    private void calcularTotalAutomatico() {
        String qtdTexto = txtQuantidade.getText().trim();
        String precoTexto = txtPrecoUnitario.getText().trim();

        if (!qtdTexto.isEmpty() && !precoTexto.isEmpty()) {
            try {
                int qtd = Integer.parseInt(qtdTexto);
                double preco = Double.parseDouble(precoTexto.replace(",", "."));
                double total = qtd * preco;
                txtValorTotal.setText(String.format("R$ %.2f", total));
            } catch (NumberFormatException e) {
                txtValorTotal.setText("R$ 0,00");
            }
        } else {
            txtValorTotal.setText("R$ 0,00");
        }
    }

