    private void tblEstoqueMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblEstoqueMouseClicked
        // TODO add your handling code here:
        int linhaSelecionada = tblEstoque.getSelectedRow();
    
    // Verifica se alguma linha foi realmente selecionada
    if (linhaSelecionada != -1) {
        // Pega a lista atual de peças para obter o ID correto da peça selecionada
        List<Peca> listaPecas = pecaDAO.listarTodas();
        Peca pecaSelecionada = listaPecas.get(linhaSelecionada);

        // Confirmação antes de eliminar
        int resposta = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente eliminar a peça: " + pecaSelecionada.getNome() + "?",
            "Confirmar Eliminação",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.WARNING_MESSAGE
        );

        if (resposta == javax.swing.JOptionPane.YES_OPTION) {
            // Elimina no banco de dados usando o ID
            boolean eliminado = pecaDAO.excluir(pecaSelecionada.getId());

            if (eliminado) {
                javax.swing.JOptionPane.showMessageDialog(this, "Peça eliminada com sucesso!");
                carregarTabelaEstoque(); // Atualiza a tabela na tela
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Erro ao eliminar a peça no banco de dados.");
            }
        }
    }
    }//GEN-LAST:event_tblEstoqueMouseClicked
 
