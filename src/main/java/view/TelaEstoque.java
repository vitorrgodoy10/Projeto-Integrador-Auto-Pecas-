    public void carregarTabelaEstoque() {
        DefaultTableModel model = (DefaultTableModel) tblEstoque.getModel();
        model.setRowCount(0);

        List<Peca> listaPecas = pecaDAO.listarTodas();

        for (Peca p : listaPecas) {
            model.addRow(new Object[]{
                p.getSku(),
                p.getNome(),
                p.getQuantidade(),
                p.getEstoqueMinimo(),
                String.format("R$ %.2f", p.getPrecoCusto()),
                String.format("R$ %.2f", p.getPrecoVenda()),
                "✏️  🗑️"
            });
        }
    }

