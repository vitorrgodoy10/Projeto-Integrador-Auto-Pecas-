    private void btnEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntrarActionPerformed
        // TODO add your handling code here:
   String usuario = txtUsuario.getText().trim();
    String senha = new String(txtSenha.getPassword());

    if (usuario.equals("admin") && senha.equals("1234")) {
        
        // <--- LÓGICA DO LEMBRAR DE MIM:
        if (chkLembrar.isSelected()) {
            prefs.put("usuario_salvo", usuario);
            prefs.putBoolean("lembrar_ativo", true);
        } else {
            prefs.remove("usuario_salvo");
            prefs.putBoolean("lembrar_ativo", false);
        }

        lblMensagemErro.setVisible(false);
        
        MenuPrincipal menu = new MenuPrincipal();
        menu.setLocationRelativeTo(null);
        menu.setVisible(true);
        
        this.dispose();
    } else {
        lblMensagemErro.setVisible(true);
    }
    }//GEN-LAST:event_btnEntrarActionPerformed

