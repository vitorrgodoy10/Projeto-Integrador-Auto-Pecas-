    /**
     * Carrega o nome do utilizador salvo anteriormente se a opção estiver ativa
     */
    private void carregarUsuarioLembrado() {
        String usuarioSalvo = prefs.get("usuario_salvo", "");
        boolean lembrarAtivo = prefs.getBoolean("lembrar_ativo", false);

        if (lembrarAtivo && !usuarioSalvo.isEmpty()) {
            txtUsuario.setText(usuarioSalvo);
            chkLembrar.setSelected(true);
        }
    }

