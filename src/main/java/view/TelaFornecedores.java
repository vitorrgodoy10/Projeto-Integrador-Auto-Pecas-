    private void tblFornecedoresMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblFornecedoresMouseClicked
        // TODO add your handling code here:
       int linhaSelecionada = tblFornecedores.getSelectedRow();
    int colunaSelecionada = tblFornecedores.getSelectedColumn();

    if (linhaSelecionada == -1) {
        return;
    }

    int id = (int) tblFornecedores.getValueAt(linhaSelecionada, 0);

    // ✏️ AÇÃO DE EDITAR (Coluna 4)
    if (colunaSelecionada == 4) {
        // 1. Procura os dados completos do fornecedor selecionado
        Fornecedor fornecedorParaEditar = fornecedorDAO.buscarPorId(id);

        if (fornecedorParaEditar != null) {
            java.awt.Frame parentFrame = (java.awt.Frame) javax.swing.SwingUtilities.getWindowAncestor(this);
            
            // 2. Abre o modal passando o fornecedor para preenchimento
            FormFornecedorModal modal = new FormFornecedorModal(parentFrame, true, fornecedorParaEditar);
            modal.setLocationRelativeTo(parentFrame);
            modal.setVisible(true);

            // 3. Recarrega a tabela após fechar a edição
            carregarTabelaFornecedores();
        }
    } 
    
    // 🗑️ AÇÃO DE EXCLUIR (Coluna 5)
    else if (colunaSelecionada == 5) {
        String razaoSocial = tblFornecedores.getValueAt(linhaSelecionada, 1).toString();

        int resposta = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente excluir o fornecedor: " + razaoSocial + "?",
            "Confirmar Exclusão",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.WARNING_MESSAGE
        );

        if (resposta == javax.swing.JOptionPane.YES_OPTION) {
            boolean deletado = fornecedorDAO.excluir(id);

            if (deletado) {
                javax.swing.JOptionPane.showMessageDialog(this, "Fornecedor excluído com sucesso!");
                carregarTabelaFornecedores();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Erro ao excluir o fornecedor no banco de dados.");
            }
        }
    }

    }//GEN-LAST:event_tblFornecedoresMouseClicked

