    public void carregarTabelaFornecedores() {
        DefaultTableModel modelo = (DefaultTableModel) tblFornecedores.getModel();
        modelo.setRowCount(0); // Limpa as linhas atuais

        List<Fornecedor> lista = fornecedorDAO.listarTodos();

        for (Fornecedor f : lista) {
            modelo.addRow(new Object[]{
                f.getId(),
                f.getRazaoSocial(),
                f.getCnpj(),
                f.getTelefone(),
                "✏️", // Coluna 4: Editar
            "🗑️"  // Coluna 5: Excluir
            });
        }
  }
