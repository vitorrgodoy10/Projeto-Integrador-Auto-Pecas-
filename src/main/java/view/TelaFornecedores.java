    for (Fornecedor f : lista) {
        if (f.getRazaoSocial().toLowerCase().contains(termo) || f.getCnpj().contains(termo)) {
            modelo.addRow(new Object[]{
                f.getId(),
                f.getRazaoSocial(),
                f.getCnpj(),
                f.getTelefone(),
               "✏️", // Coluna 4: Editar
            "🗑️"  // Coluna 5: Excluir
            });
        }
    }
